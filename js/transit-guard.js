/* حارس وميض الانتقال بين الصفحات.

   يجب أن يعمل قبل أول إطار يُرسم: إن وصلنا عبر انتقال، نضع is-entering
   على <html> فيُرسم الستار مغطّيًا الشاشة فورًا، ثم ينكشف بهدوء.
   بدونه تومض الصفحة الجديدة بيضاء للحظة قبل بدء الحركة.

   كان مضمّنًا في رأس كل صفحة، لكن سياسة CSP (script-src 'self')
   تحظر السكربتات المضمّنة — فنُقل هنا بدل إضعاف السياسة
   بـ 'unsafe-inline' الذي يفتح الباب لثغرات XSS.

   يُستدعى بلا defer ولا async ليبقى حاجزًا قبل الرسم. */
(function () {
  try {
    if (sessionStorage.getItem('md-transit') === '1') {
      document.documentElement.classList.add('is-entering');
    }
  } catch (e) {}
})();
